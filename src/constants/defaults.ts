export const UNIT_CONVERSIONS = {
  // 1 meter in various units
  toMeters: {
    meters: 1,
    feet: 0.3048,
    inches: 0.0254,
    millimeters: 0.001,
  },
  fromMeters: {
    meters: 1,
    feet: 3.28084,
    inches: 39.3701,
    millimeters: 1000,
  },
};

export function convertToMeters(val: number, unit: MeasurementUnit): number {
  return val * UNIT_CONVERSIONS.toMeters[unit];
}

export function convertFromMeters(valM: number, unit: MeasurementUnit): number {
  return valM * UNIT_CONVERSIONS.fromMeters[unit];
}

export function formatDimension(valM: number, unit: MeasurementUnit, decimals = 1): string {
  const converted = convertFromMeters(valM, unit);
  if (unit === 'feet') {
    const feet = Math.floor(converted);
    const inches = Math.round((converted - feet) * 12);
    if (inches === 12) return `${feet + 1}′-0″`;
    return `${feet}′-${inches}″`;
  }
  const suffix = unit === 'meters' ? 'm' : unit === 'inches' ? 'in' : 'mm';
  return `${converted.toFixed(decimals)} ${suffix}`;
}

export function formatArea(valM2: number, unit: MeasurementUnit): { primary: string; secondary: string } {
  const sqFt = valM2 * 10.7639;
  if (unit === 'feet' || unit === 'inches') {
    return {
      primary: `${Math.round(sqFt).toLocaleString()} sq.ft`,
      secondary: `${valM2.toFixed(1)} sq.m`,
    };
  }
  return {
    primary: `${valM2.toFixed(1)} sq.m`,
    secondary: `${Math.round(sqFt).toLocaleString()} sq.ft`,
  };
}

